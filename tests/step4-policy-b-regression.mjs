import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const dir=path.resolve(import.meta.dirname,'../docs/smart-maintenance');
const ctx=vm.createContext({console,Date,Error,TypeError,RangeError,Number,globalThis:null});ctx.globalThis=ctx;
for (const file of ['date-calculator.js','plan-policy.js','schedule-engine.js']) vm.runInContext(fs.readFileSync(path.join(dir,file),'utf8'),ctx);
const policy=ctx.SmartMaintenancePlanPolicy, engine=ctx.SmartMaintenanceScheduleEngine;
const base={id:'plan-1',equipmentId:'machine-1',intervalUnit:'day',intervalCount:7,baseDate:'2026-10-01',trackingStartedOn:'2026-10-01',scheduleBasis:'fixed'};
const revised=policy.changeSchedule(base,{intervalUnit:'day',intervalCount:10,baseDate:'2026-10-21'},'관리자','주기 수정','2026-10-21','2026-10-19T09:00:00Z','2026-10-19');
assert.equal(policy.planAt(revised,'2026-10-20').intervalCount,7);
assert.equal(policy.planAt(revised,'2026-10-21').intervalCount,10);
assert.equal(engine.isOccurrence(revised,'2026-10-22','2026-10-01'),false,'old future due replaced');
assert.equal(engine.isOccurrence(revised,'2026-10-31','2026-10-21'),true,'new future due calculated');
const done=[{id:'r1',planId:base.id,equipmentId:base.equipmentId,inspectedAt:'2026-10-08',scheduleOccurrenceDueDate:'2026-10-08',scheduleCompletionEligible:true}];
assert.deepEqual(Array.from(engine.missedDates(revised,done,'2026-11-01')),['2026-10-15','2026-10-31']);
assert.equal(engine.describeTarget(revised,done,'2026-10-22').dueDate,'2026-10-15','past missed due preserved');
const paused=policy.pause(revised,'관리자','정지','2026-10-30','2026-10-30T00:00:00Z');
assert.equal(engine.missedDates(paused,done,'2026-11-01').includes('2026-10-31'),false);
const backup=fs.readFileSync(path.join(dir,'backup.js'),'utf8');
assert.match(backup,/\['keep', '현재 정보 유지'\]/);
assert.match(backup,/\['apply', '백업 정보 적용'\]/);
assert.match(backup,/strategy\.get\(`\$\{name\}::\$\{record\.id\}`\) === 'apply'/);
assert.match(backup,/SmartMaintenanceBackupIntegrity\.verify\(proposed, allProposedRecords\)/);
assert.match(backup,/데이터가 변경됐습니다\. 백업 내용 비교를 다시 실행하세요/);
console.log('PASS: effective-date boundary, historical preservation, pause exclusion, safe restore conflict choice and integrity guard');
