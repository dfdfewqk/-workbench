import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const site=path.resolve(import.meta.dirname,'../docs/smart-maintenance');
const context=vm.createContext({globalThis:null,Set,Map,Object,Error,Array,JSON,Date,WeakSet,ArrayBuffer,Uint8Array,Math,Number,Blob});context.globalThis=context;
vm.runInContext(fs.readFileSync(path.join(site,'equipment-cleanup-model.js'),'utf8'),context);
const m=context.SmartMaintenanceCleanupModel;
const empty=()=>Object.fromEntries([...m.STORES].map(x=>[x,[]]));
const source=empty();source.equipment=[{id:'eq',name:'테스트',memo:'초기 메모',location:'A',assetCode:'T-01'}];
source.photos=[{id:'photo',equipmentId:'eq',recordId:'some',optimizedData:'123ABC',originalData:'aaa'}];
const before=m.signature(source);
for(const [store,field,next] of [['equipment','name','이름 수정'],['equipment','memo','메모 수정'],['equipment','location','B'],['photos','optimizedData','123ABD'],['photos','originalData','bbb']]){
  const clone=structuredClone(source);clone[store][0][field]=next;
  assert.notEqual(m.signature(clone),before,`${store}.${field} must invalidate deletion preview`);
}
const reordered=empty();reordered.equipment=[{assetCode:'T-01',location:'A',memo:'초기 메모',name:'테스트',id:'eq'}];
reordered.photos=[{originalData:'aaa',recordId:'some',optimizedData:'123ABC',equipmentId:'eq',id:'photo'}];
assert.equal(m.signature(reordered),before,'field insertion order must not cause false changes');
assert.throws(()=>m.signature({...source,photos:[{id:'photo',optimizedData:new Blob(['photo'])}]}),/Blob/,'unsupported binary must abort delete');
const exec=fs.readFileSync(path.join(site,'plan-execution.js'),'utf8');
const autosave=fs.readFileSync(path.join(site,'plan-autosave.js'),'utf8');
const safety=fs.readFileSync(path.join(site,'data-safety.js'),'utf8');
const dashboard=fs.readFileSync(path.join(site,'dashboard.css'),'utf8');
assert.match(exec,/const previousDisabled=new Map/);
assert.match(exec,/previousDisabled\.forEach\(\(_,control\)=>\{control\.disabled=true;\}\);/);
assert.match(exec,/try\{await commit\(record,sig\(current\.items\)\);/);
assert.match(exec,/previousDisabled\.forEach\(\(wasDisabled,control\)=>\{control\.disabled=wasDisabled;\}\);/);
assert.match(exec,/detail:\{planId:plan\.id,equipmentId:equipment\.id,dueDate,autoAdvance:afterCompletedSave\}/);
assert.match(autosave,/if \(detail\.autoAdvance\)/);
assert.match(autosave,/void prepareDraft\(seed\)/);
assert.match(autosave,/if \(current === finishedScope\) current = null/);
assert.match(safety,/objectStore\(name\)\.count\(\)/);
assert.match(safety,/options\.loadDetails\|\|\$\('sm-cleanup-panel'\)\.open/);
assert.match(safety,/model\.signature\(now\)!==signature/);
assert.match(safety,/t\.abort\(\)/);
assert.match(safety,/자동 백업이 아닙니다/);
assert.match(dashboard,/\.dashboard-action-button\{min-height:48px/);
console.log('PASS safety/UX: all-field deletion signature, after-save draft event, save locks and restoration, count-only overview, 48px touch targets');
