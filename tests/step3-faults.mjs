import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const dir=path.resolve(import.meta.dirname, '../docs/smart-maintenance');
const source=n=>fs.readFileSync(path.join(dir,n),'utf8');
const context=vm.createContext({Date,Error,JSON,Number,String,Boolean,RegExp,globalThis:null});
context.globalThis=context;
vm.runInContext(source('fault-model.js'),context,{filename:'fault-model.js'});
const m=context.SmartMaintenanceFaultModel;
const record=(id,result='failure',optIn=false)=>({id,equipmentId:'eq1',equipmentName:'컨베이어',assetCode:'CV-001',inspectedAt:'2026-10-29',inspector:'점검자',overallResult:result,cautionFaultRequested:optIn,checklistItems:[{itemId:'bearing',name:'베어링',result}]});
const normal=record('one','normal');
const caution=record('two','caution');
assert.equal(m.requiresFault(normal),false);
assert.equal(m.requiresFault(caution),false);
assert.equal(m.requiresFault({...caution,cautionFaultRequested:true}),true);
assert.equal(m.resolveInspection(normal,[]).action,'none');
const r=record('fail1');
const outcome=m.resolveInspection(r,[]);
assert.equal(outcome.action,'add');
assert.equal(r.linkedFaultId,'fault-fail1');
assert.equal(outcome.fault.status,'open');
assert.equal(outcome.fault.owner,'');
assert.equal(outcome.fault.priority,'unassessed');
assert.equal(outcome.fault.operatingState,'unverified');
assert(outcome.fault.sourceInspectionIds.includes(r.id));
const f=outcome.fault;
assert.throws(()=>m.resolveInspection(record('fail1'),[f]),/중복/);
const linked=record('fail2');linked.faultLinkId=f.id;
const joined=m.resolveInspection(linked,[f]);
assert.equal(joined.action,'put');
assert.deepEqual([...joined.fault.sourceInspectionIds],['fail1','fail2']);
assert.equal(linked.linkedFaultId,f.id);
const wrong=record('fail3');wrong.equipmentId='eq-other';wrong.faultLinkId=f.id;
assert.throws(()=>m.resolveInspection(wrong,[f]),/다른 설비/);
const proper={owner:'책임자',priority:'high',priorityDueDate:'',operatingState:'stopped',repairDueDate:'',nextReviewDate:'2026-11-06'};
const managed=m.updateFault(f,proper,'책임자','부품 점검 후 정지 조치');
assert.equal(managed.owner,'책임자');assert.equal(managed.priority,'high');assert.equal(managed.operatingState,'stopped');
assert.equal(managed.history.length,2);assert.equal(f.owner,'','original must stay unchanged');
assert.throws(()=>m.updateFault(managed,{...proper,owner:'교체자'},'타인','사유'),/기존 책임자/);
const reassigned=m.updateFault(managed,{...proper,owner:'새 책임자'},'책임자','교대 인계');
assert.equal(reassigned.owner,'새 책임자');
assert.equal(reassigned.history.at(-1).changes.owner.before,'책임자');
assert.throws(()=>m.updateFault(reassigned,{...proper,owner:'새 책임자',priority:'emergency'},'타인','변경'),/현재 관리 책임자/);
const worsened=m.addReview(reassigned,'새 책임자','worsening','누유 증가','2026-11-12');
assert.equal(worsened.worseningAlert,true);assert.equal(worsened.status,'open');
assert.throws(()=>m.dismissWorsening(worsened,'타인','해제'),/현재 책임자/);
const dismissed=m.dismissWorsening(worsened,'새 책임자','악화 경고 검토 완료');
assert.equal(dismissed.worseningAlert,false);assert.equal(dismissed.status,'open');
assert.throws(()=>m.closeFault(dismissed,'타인','완료'),/현재 관리 책임자/);
const closed=m.closeFault(dismissed,'새 책임자','베어링 교체 및 재확인 완료');
assert.equal(closed.status,'closed');assert.equal(closed.closedBy,'새 책임자');
assert.equal(closed.history.at(-1).type,'closed');
const relapse=record('relapse');const relapseOutcome=m.resolveInspection(relapse,[closed]);
assert.equal(relapseOutcome.action,'add');
assert.equal(relapseOutcome.fault.linkedPriorFaultId,closed.id);
assert.equal(relapseOutcome.fault.status,'open');
assert.throws(()=>m.updateFault(closed,proper,'새 책임자','수정'),/종료/);
assert.equal(m.flags({...f,priorityDueDate:'2026-10-01',nextReviewDate:'2026-10-02',repairDueDate:'2026-10-03'},'2026-10-29').priorityLate,true);
assert.equal(m.dateOnly('2026-02-30'),false);
// Inspect actual UI/integration sources: same transaction for inspection + fault lifecycle.
const inspection=source('inspection.js'),planned=source('plan-execution.js'),bridge=source('storage-version-bridge.js'),backup=source('backup.js'),dashboard=source('dashboard.js'),html=source('index.html');
assert.match(inspection,/\['equipment', 'inspectionRecords', 'faults'\], 'readwrite'/);
assert.match(inspection,/SmartMaintenanceFaultModel\.resolveInspection\(record, faults\)/);
assert.match(planned,/\['equipment','plans','inspectionRecords','faults'\],'readwrite'/);
assert.match(planned,/SmartMaintenanceFaultModel\.resolveInspection\(record,faults\)/);
assert.match(bridge,/Math\.max\(Number\.isInteger\(version\) \? version : 1, 6\)/);
assert.match(bridge,/createObjectStore\('faults'/);
assert.match(backup,/const VERSION = 6/);
assert.match(dashboard,/data\.faults\.filter\(f=>f\.status==='open'\)/);
assert.match(html,/data-panel="faults"/);
assert.match(html,/fault-model\.js" defer><\/script><script src="repair-model\.js" defer><\/script><script src="faults\.js"/);
console.log('PASS: new/linked/recurrent fault rules, ownership/priority/operation audit, review/worsening/closure and integrated source-store guards');
