import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'../docs/smart-maintenance');
const ctx=vm.createContext({console,Date,Error,TypeError,RangeError,Number,globalThis:null});ctx.globalThis=ctx;
for(const file of ['date-calculator.js','plan-policy.js','schedule-engine.js'])vm.runInContext(fs.readFileSync(path.join(root,file),'utf8'),ctx);
const pp=ctx.SmartMaintenancePlanPolicy,se=ctx.SmartMaintenanceScheduleEngine;
const plan={id:'p',equipmentId:'e',intervalUnit:'week',intervalCount:1,baseDate:'2026-10-01',trackingStartedOn:'2026-10-01',scheduleBasis:'fixed'};
let changed=pp.changeSchedule(plan,{intervalUnit:'week',intervalCount:2,baseDate:'2026-10-20'},'관리자','주기 변경','2026-10-20','2026-10-19T09:00:00Z','2026-10-19');
assert.equal(pp.planAt(changed,'2026-10-19').intervalCount,1);
assert.equal(pp.planAt(changed,'2026-10-20').intervalCount,2);
assert.deepEqual(Array.from(se.missedDates(changed,[],'2026-10-29')),['2026-10-08','2026-10-15']);
assert.equal(se.describeTarget(changed,[],'2026-10-29').dueDate,'2026-10-08');
const oldDone=['2026-10-08','2026-10-15'].map((date,i)=>({id:'old'+i,planId:'p',equipmentId:'e',inspectedAt:date,scheduleOccurrenceDueDate:date,scheduleCompletionEligible:true}));
assert.equal(se.describeTarget(changed,oldDone,'2026-10-29').dueDate,'2026-11-03');
assert.deepEqual(Array.from(se.missedDates(changed,oldDone,'2026-10-29')),[]);
assert.throws(()=>pp.changeSchedule(changed,{intervalCount:3},'','', '2026-10-30','now','2026-10-29'),/처리자/);
changed=pp.pause(changed,'관리자','라인 정지','2026-10-29','2026-10-29T09:00:00Z');
assert.equal(pp.isPausedAt(changed,'2026-10-29'),true);
assert.equal(se.describeTarget(changed,[],'2026-10-29').kind,'paused');
assert.throws(()=>se.executionTarget(changed,[]),/일시정지/);
changed=pp.resume(changed,'관리자','정상 재가동','2026-11-03','2026-11-03T09:00:00Z',true);
assert.equal(changed.resumeInspectionRequired,true);
assert.equal(pp.isPausedAt(changed,'2026-11-02'),true);
assert.equal(pp.isPausedAt(changed,'2026-11-03'),false);
assert.equal(se.describeTarget(changed,[],'2026-11-03').kind,'overdue');
const oldPlan={id:'old',equipmentId:'e',intervalUnit:'day',intervalCount:1,baseDate:'2026-10-01',trackingStartedOn:'2026-10-01',scheduleBasis:'fixed'};
const held=pp.pause(oldPlan,'관리자','중지','2026-10-03','2026-10-03T01:00:00Z');
const resumed=pp.resume(held,'관리자','재개','2026-10-06','2026-10-06T01:00:00Z');
assert.deepEqual(Array.from(se.missedDates(resumed,[],'2026-10-08')),['2026-10-02','2026-10-06','2026-10-07']);
assert.deepEqual(Array.from(se.pausedDates(resumed,'2026-10-08')),['2026-10-03','2026-10-04','2026-10-05']);
const history=fs.readFileSync(path.join(root,'integrated-history.js'),'utf8');
assert.match(history,/SmartMaintenanceCorrections\?\.mount/);
const correction=fs.readFileSync(path.join(root,'inspection-corrections.js'),'utf8');
assert.match(correction,/corrections=\[\.\.\.\(previous\.corrections/);
assert.match(correction,/fault\.recheckRequired=true/);
console.log('PASS: date-effective plan revisions, preserved historical missed dates, pause/resume, explicit audit, correction wiring');
