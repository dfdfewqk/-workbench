import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const base=path.resolve(import.meta.dirname,'../docs/smart-maintenance');
const scripts=fs.readdirSync(base).filter(x=>x.endsWith('.js'));
assert(scripts.length>=27,'new plan lifecycle and correction modules must be present');
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
const links=[...html.matchAll(/<script\s+src="([^"]+)"\s+defer><\/script>/g)].map(m=>m[1]);
assert.equal(new Set(links).size,links.length,'scripts must not repeat');
assert.equal(links.length,scripts.length,'every JS module must be linked from the app');
assert.deepEqual(links.filter(s=>!fs.existsSync(path.join(base,s))),[],'all linked scripts must exist');
for(const name of ['backup-integrity.js','backup.js','photos.js','storage-version-bridge.js','app.js','plan-autosave.js','plan-execution.js'])assert(links.includes(name));
assert(links.indexOf('backup-integrity.js')<links.indexOf('backup.js'),'restore verification must load first');
assert(links.indexOf('storage-version-bridge.js')<links.indexOf('app.js'),'database version bridge must load first');
const photos=fs.readFileSync(path.join(base,'photos.js'),'utf8');
assert.match(photos,/if \(!p\.hiddenAt\) \{\s*const img=/,'hidden images should not be rendered');
assert.match(photos,/숨김 사진 \(기록만 보존\)/,'hidden photo audit metadata persists');
const backup=fs.readFileSync(path.join(base,'backup.js'),'utf8');
assert.match(backup,/allProposedRecords/,'all surviving relationships must be checked before write');
assert.match(backup,/new Date\(\); return `\$\{d\.getFullYear\(\)\}/,'backup file date should use browser-local day');
console.log('PASS: complete linked-script inventory, schema compatibility guards, hidden-photo privacy, preflight and local date');
