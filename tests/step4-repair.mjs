import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const dir=path.resolve(import.meta.dirname,'../docs/smart-maintenance');
const source=name=>fs.readFileSync(path.join(dir,name),'utf8');
const ctx=vm.createContext({Date,Error,JSON,Number,String,RegExp,Boolean,Math,globalThis:null});ctx.globalThis=ctx;
for(const name of ['fault-model.js','repair-model.js'])vm.runInContext(source(name),ctx,{filename:name});
const F=ctx.SmartMaintenanceFaultModel,R=ctx.SmartMaintenanceRepairModel;
const inspection={id:'i-1',equipmentId:'eq-1',equipmentName:'컨베이어',inspector:'점검자',overallResult:'failure',checklistItems:[]};
const initial=F.newFault(inspection);
const owner=F.updateFault(initial,{owner:'관리자',priority:'high',priorityDueDate:'',operatingState:'stopped',repairDueDate:'2026-11-07',nextReviewDate:'2026-11-03'},'관리자','고장 확인');
assert.equal(R.metrics(owner).planStatus,'needed');
assert.equal(R.metrics(owner).total,0);
assert.throws(()=>R.addTask(owner,{title:'',worker:'작업A',role:'기계'},'관리자','등록'),/입력/);
assert.throws(()=>R.addTask(owner,{title:'교체',worker:'작업A',role:'기계'},'타인','등록'),/책임자/);
const planned=R.addTask(owner,{title:'베어링 교체',worker:'작업A',role:'정비'},'관리자','베어링 마모');
assert.equal(R.metrics(planned).planStatus,'draft');
assert.equal(R.metrics(planned).total,1);
assert.equal(owner.workPlan,undefined,'older fault records stay readable');
const taskId=R.tasksOf(planned)[0].id;
assert.equal(R.taskStatus(R.tasksOf(planned)[0]),'pending');
assert.throws(()=>R.confirmPlan(owner,'관리자','확정'),/작업/);
const confirmed=R.confirmPlan(planned,'관리자','정비 방안 승인');
assert.equal(R.metrics(confirmed).planStatus,'confirmed');
assert.equal(confirmed.status,'open','plan approval cannot close fault');
assert.equal(confirmed.owner,'관리자');
assert.equal(confirmed.repairDueDate,'2026-11-07');
assert.throws(()=>R.confirmPlan(confirmed,'관리자','중복'),/이미/);
const team=R.addParticipant(confirmed,taskId,'작업B','전기','관리자','전기 점검 필요');
assert.equal(R.metrics(team).planStatus,'review');
assert.equal(R.metrics(team).members,2);
assert.throws(()=>R.addParticipant(team,taskId,'작업B','정비','관리자','중복'),/이미/);
const reapproved=R.confirmPlan(team,'관리자','작업자 추가 검토');
assert.equal(R.metrics(reapproved).planStatus,'confirmed');
const task=R.tasksOf(reapproved)[0];const [p1,p2]=task.participants;
assert.throws(()=>R.updateParticipant(reapproved,taskId,p1.id,'타인','done','교체 완료','2026-10-29'),/작업자 본인/);
assert.throws(()=>R.updateParticipant(reapproved,taskId,p1.id,'작업A','done','','2026-10-29'),/수행 내용/);
const worked=R.updateParticipant(reapproved,taskId,p1.id,'작업A','done','베어링 교체 완료','2026-10-29');
assert.equal(R.taskStatus(R.tasksOf(worked)[0]),'working','one worker finishing does not finish the shared task');
assert.equal(worked.status,'open');
assert.throws(()=>F.closeFault(worked,'관리자','종료 시도'),/미완료/);
const held=R.taskAction(worked,taskId,'hold','관리자','부품 입고 대기','2026-10-01');
assert.equal(R.taskStatus(R.tasksOf(held)[0]),'held');
assert.equal(R.metrics(held,'2026-10-29').holdOverdue,1);
assert.equal(held.repairDueDate,'2026-11-07','hold must not extend original repair deadline');
assert.throws(()=>R.updateParticipant(held,taskId,p2.id,'작업B','working','',''),/보류/);
const checked=R.taskAction(held,taskId,'check','관리자','입고 지연 실제 확인','2026-11-02');
assert.equal(R.metrics(checked,'2026-10-29').holdOverdue,0);
const resumed=R.taskAction(checked,taskId,'resume','관리자','부품 입고 확인');
assert.equal(R.taskStatus(R.tasksOf(resumed)[0]),'working');
const finished=R.updateParticipant(resumed,taskId,p2.id,'작업B','done','전원 배선 재결선','2026-10-29');
assert.equal(R.taskStatus(R.tasksOf(finished)[0]),'done');
assert.equal(R.metrics(finished).pending,0);
assert.equal(finished.status,'open','all workers completed but fault remains open');
assert.throws(()=>R.taskAction(finished,taskId,'cancel','관리자','불필요'),/완료/);
assert.throws(()=>R.updateParticipant(finished,taskId,p1.id,'작업A','pending','', '', ''),/정정 사유/);
const corrected=R.updateParticipant(finished,taskId,p1.id,'작업A','done','베어링 교체 및 검사 완료','2026-10-29','작업 내용 오기 정정');
assert.equal(corrected.history.at(-1).type,'repair-participant-updated');
assert.equal(corrected.history.at(-1).before.workDetail,'베어링 교체 완료');
const completeClosed=F.closeFault(corrected,'관리자','정비 결과 확인 및 안전 절차 별도 완료');
assert.equal(completeClosed.status,'closed');
assert.throws(()=>R.addTask(completeClosed,{title:'작업',worker:'작업A',role:'정비'},'관리자','등록'),/종료/);
// Cancel a task, preserve reason, and invalidate prior approval.
const withExtra=R.addTask(reapproved,{title:'배선 교체',worker:'작업C',role:'전기'},'관리자','추가 증상');
const extraId=R.tasksOf(withExtra).at(-1).id;
assert.throws(()=>R.taskAction(withExtra,extraId,'cancel','타인','불필요'),/책임자/);
const canceled=R.taskAction(withExtra,extraId,'cancel','관리자','배선 이상이 아님');
assert.equal(R.taskStatus(R.tasksOf(canceled).at(-1)),'canceled');
assert.equal(R.tasksOf(canceled).at(-1).cancelReason,'배선 이상이 아님');
assert.equal(R.metrics(canceled).planStatus,'review');
assert.equal(R.metrics(canceled).canceled,1);
assert.equal(canceled.history.at(-1).type,'repair-task-cancel');
const exceptions=F.closeFault(canceled,'관리자','부품 교체는 별도 인계, 위험 검토 후 종료',true);
assert.equal(exceptions.status,'closed');
assert(exceptions.closureIncompleteTasks.count>0);
assert.equal(exceptions.closureIncompleteTasks.acknowledgedBy,'관리자');
// Legacy closure still works without work plan.
assert.equal(F.closeFault(owner,'관리자','오류가 아닌 것으로 판명').status,'closed');
const html=source('index.html'),ui=source('repair-ui.js'),faultUI=source('faults.js'),backup=source('backup.js');
assert.match(html,/repair-model\.js" defer><\/script><script src="faults\.js" defer><\/script><script src="repair-ui\.js"/);
assert.match(html,/id="repair-board"/);
assert.match(html,/id="fault-close-ack"/);
assert.match(faultUI,/SmartMaintenanceFaultUI=Object\.freeze\(\{updateSelected\}\)/);
assert.match(ui,/F\.updateSelected\(/);
assert.match(backup,/const VERSION = 6/);
console.log('PASS: 4th-stage plan approval, multi-worker task transitions, hold/recheck/resume, cancel, audit and closure safeguards');
